/**
 * Волны обязательной маркировки «Честный знак»: товарные группы с кодами ТН ВЭД
 * и датой, с которой нанесение кодов при импорте обязательно. Единственный кодовый
 * список curated-слоя — TKS показывает маркировку как факт (PRIZNAK=28), но не даёт
 * структурированных дат и не знает анонсированных будущих волн, а чек-лист должен
 * предупреждать заранее («станет обязательной с …»).
 *
 * Перечень групп — распоряжение Правительства РФ от 28.04.2018 № 792-р (ред.
 * расп. № 956-р от 27.04.2026); правила по группам — ПП РФ (в basis каждой записи).
 * Момент нанесения: до помещения под процедуру выпуска для внутреннего потребления
 * (ПП РФ от 26.04.2019 № 515, п. 2–4); на таможенном складе — допустимо
 * (пп. 2 п. 2 ст. 158 ТК ЕАЭС), на СВХ — нет.
 *
 * `mandatoryFrom` — дата ПЕРВОГО этапа обязательности группы (поэтапность — в note).
 * `partial: true` — перечень группы содержит «из»-позиции или критерий ТН ВЭД+ОКПД2:
 * совпадение префикса не гарантирует применимость → уверенность «проверьте».
 * Эксперименты (без утверждённой обязательности) сюда НЕ вносятся — «план, не норма».
 *
 * При добавлении волны обновляй verifiedAt; сверяй перечни с приложениями к ПП
 * в актуальной редакции, а не со статьями.
 */
export interface MarkingWave extends CuratedRecord {
  /** Товарная группа (человекочитаемо, как на честныйзнак.рф). */
  group: string;
  /** Префиксы кодов ТН ВЭД без пробелов (2–10 знаков). */
  tnVedPrefixes: string[];
  /** «из» позиция / критерий с ОКПД2: применяется частично, по описанию товара. */
  partial?: boolean;
  /** Дата обязательного нанесения кодов при вводе в оборот/импорте (ISO YYYY-MM-DD). */
  mandatoryFrom: string;
  /** Нюансы: поэтапность, исключения по упаковке и т. п. */
  note?: string;
}

