/** Волны, применимые к коду ТН ВЭД (по префиксам, без учёта дат). */
export function matchMarkingWaves(
  tnVedCode: string,
  waves: MarkingWave[] = MARKING_WAVES,
): MarkingWave[] {
  const code = String(tnVedCode ?? '').replace(/\s/g, '');
  if (!code) return [];
  return waves.filter((wave) => wave.tnVedPrefixes.some((prefix) => code.startsWith(prefix)));
}
