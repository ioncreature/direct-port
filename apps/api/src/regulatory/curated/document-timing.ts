import type { ChecklistTiming, CuratedRecord } from './interfaces';

/**
 * Timing-справочник: когда в цикле поставки получать разрешительный документ и
 * почему именно тогда. Это главная информация чек-листа, которой нет в TKS:
 * справочник знает «что требуется», но не знает, что нотификацию ФСБ надо
 * проверять до заказа, а коды «Честного знака» наносятся на фабрике.
 *
 * Сквозное правило для документов об оценке соответствия: они должны находиться
 * у декларанта на момент подачи ДТ и быть действительны на дату её регистрации
 * (Решение Совета ЕЭК от 12.11.2021 № 130). Нарушение — отказ в выпуске,
 * ст. 16.3 КоАП РФ, простой на СВХ.
 *
 * Нормативные сроки указаны с реквизитами; практические диапазоны помечены
 * «по практике» (источник — отраслевая практика на дату verifiedAt).
 */

