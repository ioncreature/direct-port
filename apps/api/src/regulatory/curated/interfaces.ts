/**
 * Курируемый слой данных для чек-листа документов к поставке — ТОЛЬКО то, чего нет
 * в TKS TNVED API физически: timing получения документов, даты волн маркировки
 * «Честный знак», состав базового пакета (ст. 108 ТК ЕАЭС) и «стоимостного досье»
 * (ст. 325 ТК ЕАЭС). Перечни ТР ТС / утильсбора / лицензирования сюда сознательно
 * НЕ дублируются: их актуальность поддерживает редакция TKS, а ручная копия в
 * репозитории протухла бы и давала ложную уверенность.
 *
 * Каждая запись несёт basis (реквизит акта либо явную пометку «по практике») и
 * verifiedAt — дату последней ручной сверки с первоисточником. При обновлении
 * данных обновляй verifiedAt.
 */

/** Когда в цикле поставки нужно получить документ (секции чек-листа). */
export type ChecklistTiming =
  | 'before_order' // до заказа / производства партии
  | 'before_shipment' // к моменту отгрузки у поставщика
  | 'for_declaration' // к подаче ДТ
  | 'on_request'; // на случай запроса таможни (ст. 325 ТК ЕАЭС)

/**
 * Уверенность пункта чек-листа:
 * - confirmed — требование безусловно (базовый пакет) либо мера совпала с кодом точно;
 * - probable  — мера, скорее всего, применима (например, будущая волна маркировки);
 * - check     — применимость зависит от свойств товара, по коду не определяется —
 *               сформулировано как «вероятно требуется, проверьте».
 */
export type ChecklistConfidence = 'confirmed' | 'probable' | 'check';

/** Общие поля каждой курируемой записи. */
export interface CuratedRecord {
  /** Правовое основание (акт + пункт) либо явная пометка «по практике». */
  basis: string;
  /** Дата последней сверки записи с первоисточником (ISO YYYY-MM-DD). */
  verifiedAt: string;
}
