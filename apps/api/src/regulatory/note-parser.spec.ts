import {
  extractAuthority,
  extractForm,
  extractRegulation,
  extractRegulationTitle,
  findAllRegulations,
  firstMeaningfulSentence,
} from './note-parser';

describe('regulatory/note-parser', () => {
  describe('extractRegulation', () => {
    it('извлекает ТР ТС из NOTE', () => {
      const note =
        'Возможно товар подлежат подтверждению соответствия требованиям технического регламента ТС "О безопасности оборудования для работы во взрывоопасных средах" (ТР ТС 012/2011)';
      expect(extractRegulation(note)).toBe('ТР ТС 012/2011');
    });

    it('извлекает ТР ЕАЭС', () => {
      const note = 'Согласно ТР ЕАЭС 037/2016 продукция подлежит ограничению по тяжёлым металлам';
      expect(extractRegulation(note)).toBe('ТР ЕАЭС 037/2016');
    });

    it('берёт первый регламент при нескольких упоминаниях', () => {
      const note = 'См. ТР ТС 020/2011, а также ТР ЕАЭС 037/2016';
      expect(extractRegulation(note)).toBe('ТР ТС 020/2011');
    });

    it('возвращает null если регламент не упомянут', () => {
      const note = 'Постановление Правительства РФ от 01.08.2024 N 1041';
      expect(extractRegulation(note)).toBeNull();
    });

    it('возвращает все уникальные регламенты в порядке появления', () => {
      const note = 'ТР ТС 020/2011 и ТР ТС 020/2011 и ТР ЕАЭС 037/2016';
      expect(findAllRegulations(note)).toEqual(['ТР ТС 020/2011', 'ТР ЕАЭС 037/2016']);
    });
  });

  describe('extractRegulationTitle', () => {
    it('берёт текст в кавычках рядом с номером регламента', () => {
      const note =
        'Возможно товар подлежат подтверждению соответствия требованиям технического регламента ТС "О безопасности оборудования для работы во взрывоопасных средах" (ТР ТС 012/2011)';
      expect(extractRegulationTitle(note, 'ТР ТС 012/2011')).toBe(
        'О безопасности оборудования для работы во взрывоопасных средах',
      );
    });

    it('возвращает null если кавычек нет', () => {
      const note = 'См. ТР ТС 020/2011 и Решение ЕЭК';
      expect(extractRegulationTitle(note, 'ТР ТС 020/2011')).toBeNull();
    });
  });

  describe('extractForm', () => {
    it('распознаёт декларирование соответствия', () => {
      expect(extractForm('Низковольтное оборудование подлежит декларированию соответствия')).toBe(
        'declaration',
      );
    });

    it('распознаёт сертификацию', () => {
      expect(
        extractForm('Продукция подлежит обязательной сертификации в соответствии с ТР ТС'),
      ).toBe('certificate');
    });

    it('распознаёт государственную регистрацию', () => {
      expect(
        extractForm('Требуется свидетельство о государственной регистрации Роспотребнадзора'),
      ).toBe('state_registration');
    });

    it('распознаёт лицензирование', () => {
      expect(extractForm('Ввоз / вывоз опасных отходов осуществляются при наличии лицензии')).toBe(
        'license',
      );
    });

    it('распознаёт разрешение / заключение', () => {
      expect(
        extractForm(
          'Закупка за границей и ввоз в РФ которых допускается при наличии разрешений Главгоссвязьнадзора',
        ),
      ).toBe('permit');
    });

    it('распознаёт утилизационный сбор', () => {
      expect(extractForm('Импортеру товаров требуется уплатить экологический сбор')).toBe('fee');
    });

    it('возвращает unknown если форма не упомянута', () => {
      expect(extractForm('Товар подсанкционный')).toBe('unknown');
    });

    it('декларирование выигрывает у общего "сертификации", если идёт первым', () => {
      const note =
        'Низковольтное оборудование подлежит подтверждению соответствия в форме декларирования соответствия. Если попадает в перечень — обязательная сертификация.';
      expect(extractForm(note)).toBe('declaration');
    });
  });

  describe('extractAuthority', () => {
    it('распознаёт Минпромторг', () => {
      expect(extractAuthority('перечень, утвержденный приказом Минпромторга России')).toBe(
        'Минпромторг России',
      );
    });

    it('распознаёт Роспотребнадзор по полному наименованию', () => {
      expect(
        extractAuthority(
          'Контроль осуществляет Федеральная служба по надзору в сфере защиты прав потребителей и благополучия человека',
        ),
      ).toBe('Роспотребнадзор');
    });

    it('распознаёт Минцифры/Роскомнадзор для РЭС', () => {
      expect(
        extractAuthority('допускается при наличии разрешений Главгоссвязьнадзора РФ'),
      ).toBe('Минцифры России / Роскомнадзор');
    });

    it('распознаёт Росприроднадзор', () => {
      expect(
        extractAuthority(
          'осуществляет Федеральная служба по надзору в сфере природопользования',
        ),
      ).toBe('Росприроднадзор');
    });

    it('возвращает null если конкретного ведомства не упомянуто', () => {
      expect(
        extractAuthority('Решение Совета ЕЭК от 12.11.2021 N 130 утвержден порядок ввоза'),
      ).toBeNull();
    });
  });

  describe('firstMeaningfulSentence', () => {
    it('убирает префикс "Внимание!"', () => {
      const note = 'Внимание! До 01.09.26г. допускается проведение оценки в форме декларирования.';
      expect(firstMeaningfulSentence(note)).toBe(
        'До 01.09.26г. допускается проведение оценки в форме декларирования.',
      );
    });

    it('возвращает первое непустое предложение из многострочного NOTE', () => {
      const note = '\r\n\r\nПервое предложение. Второе предложение.\r\n\r\nДругой блок.';
      expect(firstMeaningfulSentence(note)).toBe('Первое предложение.');
    });

    it('обрезает слишком длинное предложение многоточием', () => {
      const note = 'A'.repeat(500) + '.';
      const result = firstMeaningfulSentence(note);
      expect(result.endsWith('…')).toBe(true);
      expect(result.length).toBeLessThanOrEqual(320);
    });
  });
});
