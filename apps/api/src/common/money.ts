/**
 * Округление денежной величины до копеек (2 знака). Единая денежная политика:
 * пошлина, акциз и НДС округляются на каждом charge в валюте документа, НДС
 * считается от УЖЕ округлённой базы (таможенная стоимость + округл. пошлина +
 * округл. акциз), а итоги собираются как сумма округлённых компонентов. Так
 * Σ(построчных значений) сходится с итогом (сумма округлённых = округление суммы),
 * что критично для соответствия таможенной декларации.
 *
 * Нечисловые/бесконечные входы → 0: защита от мусорного parsedData, который иначе
 * протёк бы NaN/Infinity во все суммы (см. валидацию входов в CalculatorService).
 */
export function roundMoney(value: number): number {
  if (!Number.isFinite(value)) return 0;
  return Math.round(value * 100) / 100;
}
