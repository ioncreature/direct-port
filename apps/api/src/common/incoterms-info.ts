import { deliversInCountry, sellerPaysCarriage } from '../database/entities/document.entity';

/**
 * Описания базисов Incoterms® 2020 для генерируемых артефактов API (лист «Проект ДТ»
 * в Excel: графа 20 + справка «как базис влияет на этот документ»).
 *
 * Формулировки выверены аудитом Incoterms 2020 на соответствие правилам ICC и практике
 * таможенной стоимости при импорте в РФ (ст. 39–40 ТК ЕАЭС). Тот же набор названий
 * продублирован в UI админки (`apps/admin-web/src/lib/incoterms.ts`) — при правках держать
 * оба в синхроне. Домен-данные стоит вынести в общий `@direct-port/common` (пакет уже
 * подключён к обоим приложениям) — отложено отдельной задачей.
 */
const NAMES_RU: Record<string, string> = {
  EXW: 'Франко-завод',
  FCA: 'Франко-перевозчик',
  FAS: 'Франко вдоль борта судна',
  FOB: 'Франко борт',
  CFR: 'Стоимость и фрахт',
  CIF: 'Стоимость, страхование и фрахт',
  CPT: 'Перевозка оплачена до',
  CIP: 'Перевозка и страхование оплачены до',
  DAP: 'Поставка в месте назначения',
  DPU: 'Поставка в месте выгрузки',
  DDP: 'Поставка с оплатой пошлины',
};

/** В цену входит страхование груза продавцом. */
const INSURANCE_IN_PRICE = new Set(['CIF', 'CIP']);

/** Подпись для графы 20 «условия поставки»: «CFR — Стоимость и фрахт». */
export function incotermsGrafa20Label(code: string | null | undefined): string | null {
  if (!code) return null;
  const name = NAMES_RU[code];
  return name ? `${code} — ${name}` : code;
}

/**
 * Справка «как выбранный базис влияет на таможенную стоимость ЭТОГО документа» —
 * многострочный текст для листа «Проект ДТ». Учитывает, задан ли у документа фрахт,
 * и честно предупреждает о завышении ТС для D-терминов (перевозка по РФ после границы,
 * а у DDP — ввозные пошлины/НДС, которые инструмент не вычитает).
 */
export function incotermsCustomsValueSummary(
  code: string | null | undefined,
  hasFreight: boolean,
): string[] {
  if (!code || !NAMES_RU[code]) return [];
  const lines: string[] = [];

  if (!sellerPaysCarriage(code)) {
    // EXW/FCA/FAS/FOB — перевозку до границы оплачивает покупатель.
    lines.push('Доставку до границы ЕАЭС оплачивает покупатель — в цену товара она не входит.');
    lines.push(
      hasFreight
        ? 'Фрахт задан и включён в таможенную стоимость — структура корректна.'
        : 'Фрахт не задан — таможенная стоимость, пошлина и НДС занижены; задайте фрахт и пересчитайте.',
    );
    return lines;
  }

  // C- и D-термины — основную перевозку оплачивает продавец.
  lines.push('Основную перевозку оплачивает продавец — доставка обычно уже в цене товара и в таможенной стоимости.');
  if (INSURANCE_IN_PRICE.has(code)) {
    lines.push('Страхование груза тоже оплачивает продавец — оно уже учтено в таможенной стоимости.');
  }
  if (deliversInCountry(code)) {
    lines.push(
      `Место назначения обычно внутри РФ: в цену входит перевозка по территории РФ после границы` +
        (code === 'DDP' ? ', а также ввозные пошлины и НДС' : '') +
        `. Эти суммы в таможенную стоимость НЕ входят (п. 2 ст. 40 ТК ЕАЭС), но инструмент их не ` +
        `вычитает — при документальном выделении вычтите их вручную, иначе стоимость завышена.`,
    );
  }
  if (hasFreight) {
    lines.push('Дополнительно задан фрахт — риск двойного счёта; обнулите фрахт, если он уже в цене.');
  } else if (!deliversInCountry(code)) {
    lines.push('Отдельный фрахт задавать не нужно.');
  }
  return lines;
}
